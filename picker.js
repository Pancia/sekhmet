// --- describing elements -------------------------------------------------

function classesOf(el) {
    const all = Array.from(el.classList || []);
    const stable = all.filter(c => !isGeneratedToken(c));
    return { stable, hidden: all.length - stable.length };
}

function directText(el) {
    let t = '';
    for (const n of el.childNodes) if (n.nodeType === 3) t += n.nodeValue;
    return t.replace(/\s+/g, ' ').trim();
}

// One element as a short opening tag, with hashed classes removed and counted.
function openTag(el, showAll) {
    const bits = [el.localName];
    if (el.id) bits.push(`id="${trunc(el.id, 40)}"`);
    const { stable, hidden } = classesOf(el);
    const shown = showAll ? Array.from(el.classList) : stable;
    const extra = !showAll && hidden ? `+${hidden}` : '';
    const cls = [trunc(shown.join(' '), 60), extra].filter(Boolean).join(' ');
    if (cls) bits.push(`class="${cls}"`);
    let n = 0;
    for (const a of Array.from(el.attributes)) {
        if (NOISE_ATTR.test(a.name) || n >= 8) continue;
        const known = a.name in ATTR_SCORE || a.name.startsWith('data-') || a.name.startsWith('aria-');
        const link = a.name === 'href' || a.name === 'src';
        if (!known && !link) continue;
        bits.push(a.value === '' ? a.name : `${a.name}="${trunc(a.value, link ? 60 : 40)}"`);
        n++;
    }
    return `<${bits.join(' ')}>`;
}

const SKIP_TAGS = new Set(['script', 'style', 'noscript', 'template', 'link', 'meta']);

// The element and its contents as indented lines, kept short: long child lists
// are cut, and an svg is one line.
function treeLines(el, maxDepth, out, opts, depth = 0) {
    if (out.length >= opts.budget) return;
    const pad = '  '.repeat(depth);
    const text = directText(el);
    const mark = opts.mark && opts.mark.has(el) ? opts.mark.get(el) : '';
    out.push(`${pad}${mark}${openTag(el, opts.showAll)}${text ? ` "${trunc(text, 60)}"` : ''}`);
    if (el.localName === 'svg' || depth >= maxDepth) {
        const kids = el.children.length;
        if (kids && el.localName !== 'svg') out.push(`${pad}  … ${kids} child element${kids > 1 ? 's' : ''}`);
        return;
    }
    const kids = Array.from(el.children).filter(c => !SKIP_TAGS.has(c.localName) && c !== host);
    const shown = kids.length > 8 ? kids.slice(0, 6) : kids;
    for (const c of shown) treeLines(c, maxDepth, out, opts, depth + 1);
    if (shown.length < kids.length) out.push(`${pad}  … ${kids.length - shown.length} more`);
}

// --- building candidate rules ---------------------------------------------

function attrPart(el, name, value) {
    let score = ATTR_SCORE[name];
    if (score === undefined) {
        if (!name.startsWith('data-') || NOISE_ATTR.test(name)) return null;
        score = 45;
    }
    const tag = el.localName;
    if (value === '' || value === 'true') {
        return name.startsWith('data-') ? { sel: `${tag}[${name}]`, score: score - 10 } : null;
    }
    if (value.length > 60 || /[\n\r]/.test(value) || /^[[{]/.test(value)) return null;
    if (INSTANCE.test(value)) score = Math.min(score, 25);
    else if (name.startsWith('data-') && !/\s/.test(value) && isGeneratedToken(value)) score = Math.min(score, 20);
    const prefix = score >= 70 ? '' : tag;
    return { sel: `${prefix}[${name}="${escAttr(value)}"]`, score };
}

// Ways to name this element by itself, best first.
function selfParts(el) {
    const tag = el.localName;
    const parts = [];
    if (el.id && !isGeneratedToken(el.id)) {
        parts.push({ sel: `#${cssEsc(el.id)}`, score: INSTANCE.test(el.id) ? 25 : 85 });
    }
    for (const a of Array.from(el.attributes)) {
        const p = attrPart(el, a.name, a.value);
        if (p) parts.push(p);
    }
    if (tag === 'a') {
        const href = el.getAttribute('href') || '';
        const m = /^\/([a-z][\w-]{1,30})\//i.exec(href);
        if (m && !isGeneratedToken(m[1])) parts.push({ sel: `a[href^="/${m[1]}/"]`, score: 40 });
        try {
            const u = new URL(href, location.href);
            if (u.host && u.host !== location.host) parts.push({ sel: `a[href*="${escAttr(u.host)}"]`, score: 40 });
        } catch (_) { /* not a URL */ }
    }
    const stable = classesOf(el).stable;
    const meaningful = stable.filter(c => !UTILITY.test(c));
    for (const c of meaningful) parts.push({ sel: `${tag}.${cssEsc(c)}`, score: 50 });
    if (meaningful.length >= 2) {
        parts.push({ sel: `${tag}.${cssEsc(meaningful[0])}.${cssEsc(meaningful[1])}`, score: 55 });
    }
    return parts.sort((a, b) => b.score - a.score);
}

// tag:nth-of-type steps from `from` down to `to`. The rule of last resort,
// since any change to the page structure breaks it.
function pathBetween(from, to) {
    const steps = [];
    for (let el = to; el && el !== from; el = el.parentElement) {
        const same = Array.from(el.parentElement ? el.parentElement.children : []).filter(c => c.localName === el.localName);
        steps.unshift(same.length > 1 ? `${el.localName}:nth-of-type(${same.indexOf(el) + 1})` : el.localName);
    }
    return steps.join(' > ');
}

// Descendants that have a good name of their own, nearest first.
function namedDescendants(el, maxDepth, limit) {
    const out = [];
    const walk = (node, depth) => {
        for (const c of node.children) {
            if (out.length >= limit || SKIP_TAGS.has(c.localName)) continue;
            const p = selfParts(c)[0];
            if (p && p.score >= 45) out.push({ el: c, part: p, depth });
            if (depth < maxDepth) walk(c, depth + 1);
        }
    };
    walk(el, 1);
    return out.sort((a, b) => b.part.score - a.part.score || a.depth - b.depth);
}

// Short labels inside the element, such as "Promoted" or "Sponsored".
function shortTexts(el) {
    const seen = new Set();
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    for (let n = walker.nextNode(); n && seen.size < 12; n = walker.nextNode()) {
        if (n.parentElement && SKIP_TAGS.has(n.parentElement.localName)) continue;
        const t = n.nodeValue.replace(/\s+/g, ' ').trim();
        if (t.length >= 3 && t.length <= 30 && /[a-z]/i.test(t)) seen.add(t);
    }
    return Array.from(seen).sort((a, b) => a.length - b.length);
}

function textArg(t) {
    return /[()\/\\"']/.test(t) ? `/${t.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&')}/` : t;
}

function buildCandidates(target, examples) {
    const want = [target, ...examples];
    const out = new Map();
    const add = (sel, score, kind) => {
        if (!out.has(sel) || out.get(sel).score < score) out.set(sel, { sel, score, kind });
    };

    const own = selfParts(target);
    own.forEach(p => add(p.sel, p.score, 'own'));
    const good = own[0] && own[0].score >= 40 ? own[0] : null;
    const base = good ? good.sel : target.localName;

    let depth = 1;
    for (let a = target.parentElement; a && a !== document.documentElement && depth <= 8; a = a.parentElement, depth++) {
        const ap = selfParts(a)[0];
        if (!ap || ap.score < 40) continue;
        own.slice(0, 3).forEach(p => add(`${ap.sel} ${p.sel}`, (ap.score + p.score) / 2 + 5, 'inside'));
        if (!good) add(`${ap.sel} > ${pathBetween(a, target)}`, ap.score / 3, 'path');
    }

    for (const d of namedDescendants(target, 5, 40).slice(0, 8)) {
        add(`${base}:has(${d.part.sel})`, (d.part.score + (good ? good.score : 20)) / 2, 'contains');
        add(`${d.part.sel}:upward(${good ? good.sel : d.depth})`, d.part.score * 0.6, 'upward');
    }

    for (const t of shortTexts(target).slice(0, 3)) {
        add(`${base}:has-text(${textArg(t)})`, 35, 'text');
    }

    let anchor = target.parentElement;
    while (anchor && anchor !== document.body && !(anchor.id && !isGeneratedToken(anchor.id))) anchor = anchor.parentElement;
    anchor = anchor || document.body;
    const anchorSel = anchor === document.body ? 'body' : `#${cssEsc(anchor.id)}`;
    add(`${anchorSel} > ${pathBetween(anchor, target)}`, 1, 'path');

    const scored = [];
    const bySet = new Map();
    for (const c of out.values()) {
        const res = evaluate(c.sel, document);
        if (!res.els || !want.every(w => res.els.includes(w))) continue;
        c.count = res.els.length;
        // Two rules that hide exactly the same things: keep the sturdier one.
        // Per kind, so a text-based rule survives next to an id-based one that
        // hides the same things today: they break in different ways.
        const sig = `${c.kind}|${c.count}|${res.els.slice(0, 20).map(elId).join(',')}|${elId(res.els[c.count - 1])}`;
        // Text and contents rules are kept apart even then: which label to key
        // on ("Shoes" or "Promoted") is the user's call, not a score's.
        const prior = c.kind === 'text' || c.kind === 'contains' ? null : bySet.get(sig);
        if (prior && prior.score >= c.score) continue;
        if (prior) scored.splice(scored.indexOf(prior), 1);
        bySet.set(sig, c);
        scored.push(c);
    }
    return scored.sort((a, b) => b.score - a.score || a.count - b.count).slice(0, 12);
}

const ids = new WeakMap();
let nextId = 1;
function elId(el) {
    if (!ids.has(el)) ids.set(el, nextId++);
    return ids.get(el);
}

// --- what Claude gets ---------------------------------------------------------

function contextFor(target, examples, candidates) {
    const lines = [];
    const chain = [];
    for (let a = target.parentElement; a && a !== document.documentElement; a = a.parentElement) chain.unshift(a);
    lines.push('Ancestors of the picked element, outermost first:');
    chain.slice(-12).forEach((a, i) => lines.push(`${'  '.repeat(i)}${openTag(a)}`));

    lines.push('', 'The picked element and what it contains:');
    treeLines(target, 4, lines, { budget: lines.length + 80 });

    const parent = target.parentElement;
    if (parent) {
        const sibs = Array.from(parent.children).filter(c => c !== host && !SKIP_TAGS.has(c.localName));
        lines.push('', `Children of its parent (${sibs.length}), picked one marked >:`);
        sibs.slice(0, 12).forEach(s => lines.push(`${s === target ? '> ' : '  '}${openTag(s)}${directText(s) ? ` "${trunc(directText(s), 40)}"` : ''}`));
        if (sibs.length > 12) lines.push(`  … ${sibs.length - 12} more`);
    }

    examples.forEach((ex, i) => {
        lines.push('', `Example ${i + 2}, which the user also wants hidden:`);
        treeLines(ex, 2, lines, { budget: lines.length + 25 });
    });

    lines.push('', 'Rules found by a simple heuristic, with how many elements each matches on this page:');
    candidates.forEach(c => lines.push(`  ${c.count}  ${c.sel}`));
    return lines.join('\n').slice(0, 30000);
}

