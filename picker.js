let drawQueued = false;
function draw() {
    if (drawQueued) return;
    drawQueued = true;
    requestAnimationFrame(() => { drawQueued = false; drawNow(); });
}

function drawNow() {
    if (!layer) return;
    const boxes = [];
    const add = (el, cls) => {
        if (!el || !el.isConnected) return;
        const r = el.getBoundingClientRect();
        if (!r.width && !r.height) return;
        if (r.bottom < 0 || r.top > innerHeight || r.right < 0 || r.left > innerWidth) return;
        boxes.push(h('div', { class: `box ${cls}`, style: `left:${r.left}px;top:${r.top}px;width:${r.width}px;height:${r.height}px` }));
    };
    (state.preview || []).slice(0, 300).forEach(el => add(el, 'match'));
    state.examples.forEach(el => add(el, 'example'));
    add(state.target, 'target');
    if (state.mode && state.hovered) {
        add(state.hovered, state.mode === 'example' ? 'example' : 'hover');
        const r = state.hovered.getBoundingClientRect();
        boxes.push(h('div', { class: 'tag', style: `left:${Math.max(0, r.left)}px;top:${Math.max(0, r.top - 18)}px` }, openTag(state.hovered)));
    }
    layer.replaceChildren(...boxes);
}

// --- page events --------------------------------------------------------------

function fromUs(e) {
    return e.composedPath().includes(host);
}

function pageTarget(e) {
    // elementFromPoint, not e.target: our layer has no pointer events, but a
    // page overlay with pointer-events:none would otherwise be skipped too.
    const el = document.elementFromPoint(e.clientX, e.clientY);
    return el && el !== host && el !== document.documentElement ? el : null;
}

function onMove(e) {
    if (!state.mode || fromUs(e)) return;
    const el = pageTarget(e);
    if (el !== state.hovered) { state.hovered = el; draw(); }
}

function onClick(e) {
    if (!state.mode || fromUs(e)) return;
    e.preventDefault();
    e.stopImmediatePropagation();
    if (e.type !== 'click') return;
    const el = pageTarget(e);
    if (!el) return;
    if (state.mode === 'example' && state.target) {
        const t = state.target;
        if (el !== t && !el.contains(t) && !t.contains(el) && !state.examples.includes(el)) state.examples.push(el);
        setMode(null);
        recompute();
    } else {
        setMode(null);
        select(el);
    }
}

function onKey(e) {
    const inField = fromUs(e) && /^(INPUT|TEXTAREA)$/.test((e.composedPath()[0] || {}).tagName || '');
    if (e.key === 'Escape') {
        e.preventDefault();
        e.stopImmediatePropagation();
        if (state.mode && state.target) setMode(null);
        else stop();
        return;
    }
    const dir = { ArrowUp: 'up', ArrowDown: 'down', ArrowLeft: 'left', ArrowRight: 'right' }[e.key];
    if (inField || !state.target || !dir || e.altKey || e.ctrlKey || e.metaKey) return;
    e.preventDefault();
    e.stopImmediatePropagation();
    navigate(dir);
}

// Moves the selection one step: the arrow keys and the buttons under the
// element names both come here.
function navigate(dir) {
    const t = state.target;
    if (!t) return;
    const usable = el => el && el !== host && !SKIP_TAGS.has(el.localName);
    let next = null;
    if (dir === 'up') {
        if (t.parentElement && t.parentElement !== document.documentElement) {
            state.downPath.push(t);
            next = t.parentElement;
        }
    } else if (dir === 'down') {
        const back = state.downPath[state.downPath.length - 1];
        if (back && back.parentElement === t) { state.downPath.pop(); next = back; }
        else { next = Array.from(t.children).find(usable) || null; state.downPath = []; }
    } else {
        const step = dir === 'left' ? 'previousElementSibling' : 'nextElementSibling';
        next = t[step];
        while (next && !usable(next)) next = next[step];
        state.downPath = [];
    }
    if (next) select(next, true);
}

