// The header drags the panel anywhere on screen, kept fully inside the window.
function startDrag(e) {
    if (e.button !== 0 || e.target.closest('button')) return;
    e.preventDefault();
    const head = e.currentTarget;
    const r = panel.getBoundingClientRect();
    const dx = e.clientX - r.left, dy = e.clientY - r.top;
    try { head.setPointerCapture(e.pointerId); } catch (_) { /* synthetic events have no pointer */ }
    const move = ev => {
        const x = Math.min(Math.max(0, ev.clientX - dx), Math.max(0, innerWidth - r.width));
        const y = Math.min(Math.max(0, ev.clientY - dy), Math.max(0, innerHeight - 60));
        Object.assign(panel.style, {
            left: `${x}px`, top: `${y}px`, right: 'auto', bottom: 'auto',
            maxHeight: `${innerHeight - y - 12}px`,
        });
    };
    const up = () => {
        head.removeEventListener('pointermove', move);
        head.removeEventListener('pointerup', up);
        head.removeEventListener('pointercancel', up);
    };
    head.addEventListener('pointermove', move);
    head.addEventListener('pointerup', up);
    head.addEventListener('pointercancel', up);
}

const listeners = [
    ['mousemove', onMove], ['click', onClick], ['mousedown', onClick], ['mouseup', onClick],
    ['pointerdown', onClick], ['pointerup', onClick], ['dblclick', onClick], ['contextmenu', onClick],
    ['keydown', onKey], ['scroll', onScroll], ['resize', onScroll],
];

function attach() {
    for (const [type, fn] of listeners) window.addEventListener(type, fn, true);
}

function detach() {
    for (const [type, fn] of listeners) window.removeEventListener(type, fn, true);
    document.documentElement.style.cursor = '';
}

