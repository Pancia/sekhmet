function updateEdit() {
    const sel = ui.input.value.trim();
    if (!sel) { ui.editCount.textContent = ''; return; }
    const res = evaluate(sel, document);
    ui.editCount.textContent = res.els ? String(res.els.length) : res.unsupported ? '?' : '✕';
    ui.editCount.className = 'count' + (res.els && res.els.includes(state.target) ? '' : ' bad');
    ui.editCount.title = res.els ? `${res.els.length} elements on this page`
        : res.unsupported ? `:${res.unsupported}() cannot be counted here; uBlock may still accept it` : res.error;
}

async function copyRule(sel) {
    sel = (sel || '').trim();
    if (!sel) return;
    const text = toFilter(location.hostname, sel);
    const ok = await copyText(text);
    ui.status.className = 'status ' + (ok ? 'ok' : 'err');
    ui.status.textContent = ok ? `Copied. Paste into uBlock → My filters: ${text}` : `Could not copy. Select and copy by hand: ${text}`;
}

async function copyText(text) {
    try {
        await navigator.clipboard.writeText(text);
        return true;
    } catch (_) { /* falls back below: no permission, or not a secure page */ }
    try {
        const ta = document.createElement('textarea');
        ta.value = text;
        ta.style.cssText = 'position:fixed;left:-9999px;top:0';
        document.body.appendChild(ta);
        ta.select();
        const ok = document.execCommand('copy');
        ta.remove();
        return ok;
    } catch (_) {
        return false;
    }
}

async function askClaude() {
    if (!state.target || state.busy) return;
    if (!api) {
        setClaudeStatus('err', 'The extension connection is gone. Reload the page and try again.');
        return;
    }
    state.busy = true;
    ui.ask.disabled = true;
    setClaudeStatus('', 'Asking Claude…');
    const payload = {
        host: location.hostname,
        path: location.pathname,
        goal: ui.goal.value.trim(),
        context: contextFor(state.target, state.examples, state.candidates),
    };
    const t0 = Date.now();
    try {
        const res = await api.runtime.sendMessage({ action: 'pickerAskClaude', payload });
        if (!res || !res.ok) throw new Error(res && res.error ? res.error : 'no reply');
        // Best first, as Claude ranked them; its pick goes to the top and into
        // the editor, ready to copy.
        const list = (res.suggestions || []).map((s, i) => ({ ...s, rank: i + 1 }));
        const rec = Number.isInteger(res.recommended) ? list.find(s => s.rank === res.recommended) : null;
        state.claude = rec ? [rec, ...list.filter(s => s !== rec)] : list;
        if (rec) {
            state.chosen = rec.selector;
            ui.input.value = rec.selector;
            updateEdit();
            highlightChosen();
        }
        ui.claudeList.replaceChildren(...state.claude.map(s =>
            ruleRow(s.selector, null, s.why, { rank: s.rank, recommended: s === rec })));
        const secs = Math.round((Date.now() - t0) / 1000);
        setClaudeStatus('ok', [rec && res.recommendation ? `Recommended: ${res.recommendation}` : `${list.length} suggestions, best first.`,
            res.note, `(${secs}s)`].filter(Boolean).join(' '));
    } catch (err) {
        const msg = String(err && err.message || err);
        setClaudeStatus('err', /native messaging host not found|not found/i.test(msg)
            ? 'The picker helper is not installed. Run native-host/install.sh <extension-id>, then restart the browser.'
            : `Claude failed: ${msg}`);
    } finally {
        state.busy = false;
        ui.ask.disabled = false;
    }
}

function setClaudeStatus(kind, text) {
    ui.claudeStatus.className = 'status' + (kind ? ' ' + kind : '');
    ui.claudeStatus.textContent = text;
}

